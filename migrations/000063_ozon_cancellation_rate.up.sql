-- Доля отмен по кабинету, измеренная по статусам отправлений.
--
-- Потолок «ДРР от общего оборота» выводится из маржи с поправкой на выкуп, но
-- сам выкуп до сих пор был допущением в 90 %: аналитика Ozon отдаёт ЗАКАЗЫ, а
-- отмены и возвраты из них не вычтены. Проверить это было нечем — статуса не
-- было ни в одной таблице.
--
-- Оказалось, статус приходит в ответе /v2/posting/fbo/list и /v3/posting/fbs/list,
-- которые синк и так забирает каждый цикл: разборщик просто его не читал.
-- Здесь хранится измеренная доля, чтобы потолок опирался на факт, а не на цифру
-- из воздуха.
--
-- ВАЖНО: это доля ОТМЕН, а не полный выкуп — возвраты после доставки сюда не
-- попадают, для них нужен отдельный отчёт /v1/returns/list. Поэтому измеренная
-- величина — верхняя оценка выкупа.
CREATE TABLE ozon_cancellation_rates (
    seller_cabinet_id   UUID        PRIMARY KEY REFERENCES seller_cabinets(id) ON DELETE CASCADE,
    window_days         INTEGER     NOT NULL,
    total_postings      INTEGER     NOT NULL,
    cancelled_postings  INTEGER     NOT NULL,
    measured_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE ozon_cancellation_rates IS
    'Доля отменённых отправлений по кабинету за окно синка; верхняя оценка выкупа (возвраты не учтены)';
